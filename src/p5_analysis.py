"""
Phase 5: affordability analysis (runs sql/p5_analysis.sql) and writes the insights.

INPUT   data/interim/rent_by_nta.csv, commute_times.csv, se_nta_crosswalk.csv,
        rent_summary (already in DuckDB), data/reference/campuses.csv
OUTPUT  DuckDB tables: options, affordability, nta_popularity, swaps, scenario_summary
        data/interim/affordability.csv, swaps.csv, scenario_summary.csv(.xlsx)
        docs/INSIGHTS.md   auto-generated findings, every number pulled from the data

Run from the project folder (after Phases 2-4):
    python src/p5_analysis.py
"""
import duckdb
import pandas as pd

import config


def load_inputs(con) -> None:
    for table, file in [("rent_by_nta", "rent_by_nta.csv"),
                        ("commute", "commute_times.csv"),
                        ("crosswalk", "se_nta_crosswalk.csv")]:
        path = (config.DATA_INTERIM / file).as_posix()
        con.execute(f"CREATE OR REPLACE TABLE {table} AS "
                    f"SELECT * FROM read_csv('{path}', header = true)")
    path = config.CAMPUSES_FILE.as_posix()
    con.execute(f"CREATE OR REPLACE TABLE campuses AS SELECT * FROM read_csv('{path}', header = true)")

    budgets = pd.DataFrame({"budget": config.BUDGETS})
    limits = pd.DataFrame({"limit_min": config.COMMUTE_LIMITS})
    con.execute("CREATE OR REPLACE TABLE budgets AS SELECT * FROM budgets")
    con.execute("CREATE OR REPLACE TABLE commute_limits AS SELECT * FROM limits")
    con.execute("CREATE OR REPLACE TABLE params5 AS SELECT ?::INTEGER AS top_n, "
                "?::DOUBLE AS max_extra_min", [config.POPULAR_TOP_N, config.MAX_EXTRA_MIN])


def money(x) -> str:
    return f"${x:,.0f}"


def write_insights(con) -> str:
    home = con.execute("SELECT campus_id, campus_name FROM campuses "
                       "WHERE is_home_campus LIMIT 1").fetchone()
    assert home, "set is_home_campus = TRUE for one campus in data/reference/campuses.csv"
    home_id, home_name = home
    limit = config.DEFAULT_COMMUTE_LIMIT
    beds = config.HEADLINE_BEDROOMS
    lines = [f"# Insights (auto-generated by `src/p5_analysis.py`)", "",
             f"Home campus: **{home_name}**. Commute limit: **{limit} min** door to door. "
             f"Rents are 12-month medians of StreetEasy asking rents, per person. "
             f"Only rents with high/medium reliability and commutes the subway model can "
             f"handle are used. Re-run the pipeline to refresh every number below.", ""]

    # --- Headline: the biggest robust swap ---------------------------------
    # Comparing against luxury areas ("don't live in Hudson Yards") is true but
    # unsurprising, so the headline only compares against popular NTAs at or
    # below the MEDIAN rent of the popular list, i.e. a typical popular area (D-024).
    luxury_cutoff = con.execute("""
        SELECT quantile_cont(r.rent_per_person, 0.5) + 0.01
        FROM rent_by_nta r JOIN nta_popularity p USING (nta2020)
        WHERE r.bedrooms = ? AND p.popularity_rank <= (SELECT top_n FROM params5)
    """, [beds]).fetchone()[0]
    sw = con.execute("""
        SELECT * FROM swaps
        WHERE campus_id = ? AND bedrooms = ?
          AND alternative_rent_reliability = 'high'
          AND popular_commute_min <= ? AND alternative_commute_min <= ?
          AND popular_rent < ?
        ORDER BY monthly_savings DESC
    """, [home_id, beds, limit, limit, luxury_cutoff]).df()
    lines += ["## Headline", "",
              f"*Rule: the biggest saving vs. a popular NTA, where the alternative has high-reliability "
              f"rent, both commutes are ≤ {limit} min, and the popular NTA is a *typical* one: at or "
              f"below the median rent of the {config.POPULAR_TOP_N} popular NTAs "
              f"({beds.upper()} per person ≤ {money(luxury_cutoff)}).*", ""]
    if sw.empty:
        lines += ["No robust swap found within the limits for this campus.", ""]
    else:
        s = sw.iloc[0]
        extra = int(s.extra_minutes_one_way)
        plural = lambda n: "minute" if abs(n) == 1 else "minutes"
        time_phrase = (f"for **{extra} extra {plural(extra)}** each way" if extra > 0
                       else "with a commute that's **no longer**" if extra == 0
                       else f"while commuting **{-extra} {plural(extra)} less** each way")
        lines += [f"> Students at {home_name} sharing a {beds.upper()} can save "
                  f"**{money(s.monthly_savings)}/month ({money(s.monthly_savings * 12)}/year)** "
                  f"by living in **{s.alternative_nta}** instead of **{s.popular_nta}**, "
                  f"{time_phrase} ({int(s.popular_commute_min)} → "
                  f"{int(s.alternative_commute_min)} min, via {s.alternative_lines}).", ""]

        faster = sw[sw["extra_minutes_one_way"] <= 0]
        if not faster.empty:
            lines += ["**Cheaper *and* no slower** (popular areas that are simply beaten):", ""]
            for f in faster.itertuples():
                lines.append(f"- {f.popular_nta} ({money(f.popular_rent)}, {int(f.popular_commute_min)} min) → "
                             f"{f.alternative_nta} ({money(f.alternative_rent)}, "
                             f"{int(f.alternative_commute_min)} min): save {money(f.monthly_savings)}/month")
            lines.append("")

    # --- Budget reality check ---------------------------------------------
    sc = con.execute("""
        SELECT bedrooms, budget, ntas_affordable_and_reachable AS n, ntas_reachable
        FROM scenario_summary WHERE campus_id = ? AND limit_min = ?
        ORDER BY budget, bedrooms
    """, [home_id, limit]).df()
    pivot = sc.pivot(index="bedrooms", columns="budget", values="n")
    order = ["studio", "1br", "2br", "3br_plus", "any (cheapest)"]
    pivot = pivot.reindex([o for o in order if o in pivot.index])
    reachable = int(sc["ntas_reachable"].max())
    lines += ["## How many neighborhoods work?", "",
              f"NTAs within {limit} min of {home_name} that are affordable at each budget "
              f"(out of {reachable} reachable NTAs):", "",
              "| Housing | " + " | ".join(f"≤ {money(b)}" for b in pivot.columns) + " |",
              "|---|" + "---|" * len(pivot.columns)]
    for b, row in pivot.iterrows():
        lines.append(f"| {b} | " + " | ".join(str(int(v)) for v in row) + " |")
    lines.append("")

    # --- Best value frontier -------------------------------------------------
    bv = con.execute("""
        SELECT ntaname, rent_per_person, round(commute_min) AS commute_min, cheapest_type, lines
        FROM affordability
        WHERE campus_id = ? AND bedrooms = 'any (cheapest)' AND is_best_value AND commute_min <= ?
        ORDER BY commute_min
    """, [home_id, limit]).df()
    lines += ["## Best-value frontier", "",
              f"Cheapest way to live in each NTA (any housing type). These NTAs are not beaten "
              f"by any other on *both* rent and commute (within {limit} min):", "",
              "| NTA | Rent / person | Commute | Housing | Lines |", "|---|---|---|---|---|"]
    for r in bv.itertuples():
        lines.append(f"| {r.ntaname} | {money(r.rent_per_person)} | {int(r.commute_min)} min | "
                     f"{r.cheapest_type} | {r.lines} |")
    lines.append("")

    # --- Biggest swaps for every campus -------------------------------------
    allc = con.execute("""
        SELECT campus_name, popular_nta, alternative_nta, monthly_savings, extra_minutes_one_way
        FROM swaps
        WHERE bedrooms = ? AND alternative_rent_reliability = 'high'
          AND popular_commute_min <= ? AND alternative_commute_min <= ?
          AND popular_rent < ?
        QUALIFY row_number() OVER (PARTITION BY campus_id ORDER BY monthly_savings DESC) = 1
        ORDER BY monthly_savings DESC
    """, [beds, limit, limit, luxury_cutoff]).df()
    lines += [f"## Biggest swap for every campus ({beds.upper()}, both options ≤ {limit} min)", "",
              "| Campus | Instead of | Live in | Save / month | Extra min |", "|---|---|---|---|---|"]
    for r in allc.itertuples():
        lines.append(f"| {r.campus_name} | {r.popular_nta} | {r.alternative_nta} | "
                     f"{money(r.monthly_savings)} | {int(r.extra_minutes_one_way)} |")
    lines += ["", "## Caveats", "",
              "- Asking rents over-represent new and market-rate units (D-011). Real tenants often pay less.",
              "- Commutes are modelled from one point per NTA with scheduled AM-peak service (D-017 to D-020); "
              "real trips vary with delays and exactly where you live.",
              "- Areas that need a bus or LIRR are excluded from \"reachable\", not counted as unreachable.",
              "- \"Popular\" = most rental listings, a proxy for where renters look, not a survey of students."]
    text = "\n".join(lines) + "\n"
    (config.ROOT / "docs" / "INSIGHTS.md").write_text(text, encoding="utf-8")
    return text


def main() -> None:
    con = duckdb.connect(str(config.DB_PATH))
    load_inputs(con)
    con.execute((config.SQL_DIR / "p5_analysis.sql").read_text())

    for table in ["affordability", "swaps", "scenario_summary", "nta_popularity"]:
        df = con.sql(f"SELECT * FROM {table}").df()
        df.to_csv(config.DATA_INTERIM / f"{table}.csv", index=False)
        print(f"{table}: {len(df):,} rows")
    con.sql("SELECT * FROM scenario_summary").df().to_excel(
        config.DATA_INTERIM / "scenario_summary.xlsx", index=False)

    print("\n" + write_insights(con))


if __name__ == "__main__":
    main()
